    /** Lowers an expression; aggregates always come back as lvalues. Returns null for void calls. */
    private String lower(Expr e) {
        return switch (e) {
            case IntLit i -> Type.isFloat(i.type) ? floatLiteral(i.floatValue(Type.kind(i.type)), Type.kind(i.type))
                : intLiteral(i.value.longValue(), Type.kind(i.type));
            case FloatLit f -> floatLiteral(f.valueAs(Type.kind(f.type)), Type.kind(f.type));
            case StrLit s -> strLiteral(s.value);
            case BoolLit b -> b.value ? "true" : "false";
            case Name n -> n.local != null ? varRef(n.local) : "al_c_" + n.constant.name;
            case FieldAccess f -> {
                if (f.variant == null && f.target.type instanceof Type.TupleT) {
                    yield "(" + lower(f.target) + ").e" + f.fieldIndex;
                }
                if (f.variant == null) {
                    StructDecl d = ((Type.StructT) f.target.type).decl();
                    yield "(" + lower(f.target) + ").f_" + d.fields.get(f.fieldIndex).name;
                }
                String t = tmp(f.type, "{0}");
                emit(t + ".tag = " + f.variant.index + "u;");
                yield t;
            }
            case Index ix -> index(ix);
            case Call c -> c.builtin != null ? builtin(c) : call(c);
            case VariantCall v -> {
                List<String> vals = new ArrayList<>();
                for (int i = 0; i < v.args.size(); i++) {
                    Expr a = v.args.get(i).expr();
                    vals.add(coerce(lower(a), a.type, v.variant.payload.get(i)));
                }
                String t = tmp(v.type, "{0}");
                emit(t + ".tag = " + v.variant.index + "u;");
                for (int i = 0; i < vals.size(); i++) emit(t + ".u.v_" + v.variant.name + ".p" + i + " = " + vals.get(i) + ";");
                yield t;
            }
            case StructLit s -> {
                String[] given = new String[s.fields.size()];
                for (int i = 0; i < given.length; i++) {
                    FieldInit fi = s.fields.get(i);
                    Type ft = s.decl.fields.get(s.decl.fieldIndex(fi.name())).type;
                    given[i] = coerce(lower(fi.value()), fi.value().type, ft);
                }
                String t = tmp(s.type, "{0}");
                for (int i = 0; i < s.decl.fields.size(); i++) {
                    emit(t + ".f_" + s.decl.fields.get(i).name + " = " + given[s.order[i]] + ";");
                }
                yield t;
            }
            case Convert c -> convert(c);
            case Resize r -> resize(r);
            case Unary u -> {
                String v = lower(u.operand);
                PrimKind k = Type.kind(u.type);
                // Each result goes into a temporary, so a chain such as `not not ... not b` stays flat in C:
                // nested as an expression it took two parentheses per `not`, and a contract of 128 of them
                // went past the 256 levels that clang accepts.
                yield switch (u.op) {
                    case NOT -> tmp(u.type, "!(" + v + ")");
                    case NEG -> tmp(u.type, k.isFloat ? "(" + cPrim(k) + ")-(" + v + ")" : "al_neg_" + k.name + "(" + v + ", " + loc(u.span) + ")");
                    case BNOT -> tmp(u.type, "al_bnot_" + k.name + "(" + v + ")");
                };
            }
            case Binary b -> binary(b);
            case ArrayLit a when a.type instanceof Type.MapT mt -> {
                String r = tmp(mt, "{0}");
                String m = keyedFns(mt);
                Type entry = new Type.TupleT(List.of(mt.key(), mt.value()));
                for (Expr x : a.elems) {
                    String pair = coerce(lower(x), x.type, entry);
                    emit("*al_put_" + m + "(&" + r + ", &(" + pair + ").e0, " + loc(a.span) + ") = (" + pair + ").e1;");
                }
                yield r;
            }
            case ArrayLit a when a.type instanceof Type.SetT st -> {
                String r = tmp(st, "{0}");
                String m = keyedFns(st);
                for (Expr x : a.elems) emit("al_ins_" + m + "(&" + r + ", &" + keyLvalue(x, st.elem()) + ", " + loc(a.span) + ");");
                yield r;
            }
            case ArrayLit a -> {
                Type elem = Type.elementOf(a.type);
                List<String> vals = new ArrayList<>();
                for (Expr x : a.elems) vals.add(coerce(lower(x), x.type, elem));
                String t = tmp(a.type, "{0}");
                for (int i = 0; i < vals.size(); i++) emit(t + ".v[" + i + "] = " + vals.get(i) + ";");
                if (a.type instanceof Type.ListT) emit(t + ".len = " + vals.size() + "u;");
                yield t;
            }
            case TupleLit t -> {
                List<Type> elems = ((Type.TupleT) t.type).elems();
                List<String> vals = new ArrayList<>();
                for (int i = 0; i < t.elems.size(); i++) {
                    Expr x = t.elems.get(i);
                    vals.add(coerce(lower(x), x.type, elems.get(i)));
                }
                String r = tmp(t.type, "{0}");
                for (int i = 0; i < vals.size(); i++) emit(r + ".e" + i + " = " + vals.get(i) + ";");
                yield r;
            }
            case IfExpr i -> {
                String r = tmp(i.type, zeroInit(i.type));
                String c = lower(i.cond);
                open("if (" + c + ") {");
                emit(r + " = " + coerce(lower(i.then), i.then.type, i.type) + ";");
                close("} else {");
                indent++;
                emit(r + " = " + coerce(lower(i.otherwise), i.otherwise.type, i.type) + ";");
                close("}");
                yield r;
            }
            case Repeat r -> {
                Type elem = Type.elementOf(r.type);
                String v = coerce(lower(r.value), r.value.type, elem);
                // An aggregate is already in a variable or temporary that nothing changes during the fill.
                String val = Type.isAggregate(elem) ? v : tmp(elem, v);
                String t = tmp(r.type, "{0}");
                String i = "t" + ++tmpCount;
                emit("{");
                emit("    uint32_t " + i + ";");
                emit("    for (" + i + " = 0; " + i + " < " + r.n + "u; " + i + "++) " + t + ".v[" + i + "] = " + val + ";");
                emit("}");
                if (r.type instanceof Type.ListT) emit(t + ".len = " + r.n + "u;");
                yield t;
            }
        };
    }

    /** Like {@link #lower} but guarantees an lvalue (needed to take addresses or format). */
    private String lowerLvalue(Expr e) {
        String v = lower(e);
        if (e.type instanceof Type.Prim) return tmp(e.type, v);
        return v;
    }

    /**
     * The line and column the generated C passes to a trap. A line in the k-th imported file is passed as
     * -(1048576 * k + line), and al_trap_end shows it with that file's path (Frontend keeps imported files
     * under 1048576 lines).
     */
    private String loc(Span s) {
        int k = s.file() == null ? 0 : program.files.indexOf(s.file());
        long line = k <= 0 ? s.line() : -(1048576L * k + s.line());
        return line + ", " + s.col();
    }

    /** A key, value or element of a map or set, as an lvalue of type {@code to} whose address the helpers take. */
    private String keyLvalue(Expr e, Type to) {
        return Type.isAggregate(to) ? coerce(lower(e), e.type, to) : tmp(to, lower(e));
    }

    private String index(Index ix) {
        if (ix.target.type instanceof Type.MapT mt) {
            // Read through a pointer: a const one, cast for the places that are written (the checker allows that only
            // on a variable or a `mut` parameter).
            String base = lower(ix.target);
            String key = keyLvalue(ix.index, mt.key());
            String m = keyedFns(mt);
            return "(*(" + ct(mt.value()) + " *)al_get_" + m + "(&(" + base + "), &" + key + ", " + loc(ix.span) + "))";
        }
        String base = lower(ix.target);
        String idx = lower(ix.index);
        PrimKind k = Type.kind(ix.index.type);
        Type tt = ix.target.type;
        String len = tt instanceof Type.ArrayT a ? a.len() + "u" : "(" + base + ").len";
        String check = k.signed ? "al_idx_s((int64_t)(" + idx + "), " + len + ", " + loc(ix.span) + ")"
            : "al_idx_u((uint64_t)(" + idx + "), " + len + ", " + loc(ix.span) + ")";
        String i = "t" + ++tmpCount;
        emit("uint32_t " + i + " = " + check + ";");
        return "(" + base + ")." + (tt instanceof Type.Str ? "b" : "v") + "[" + i + "]";
    }

    private String call(Call c) {
        FnDecl f = c.fn;
        List<String> args = new ArrayList<>();
        for (int i = 0; i < c.args.size(); i++) {
            LocalVar p = f.paramVars.get(i);
            Expr a = c.args.get(i).expr();
            if (p.type instanceof Type.FnT) continue;
            if (p.byRef) {
                args.add("&(" + lower(a) + ")");
            } else if (Type.isAggregate(p.type)) {
                args.add("&(" + coerce(lower(a), a.type, p.type) + ")");
            } else {
                args.add(lower(a));
            }
        }
        if (!f.requires.isEmpty()) {
            args.add(loc(c.span));
        }
        String call = fnName(f) + "(" + String.join(", ", args) + ")";
        if (f.ret instanceof Type.Void) {
            emit(call + ";");
            return null;
        }
        return tmp(f.ret, call);
    }

    /**
     * Lowers a value that print or append writes, or that pad_left or pad_right pads, and returns what writes
     * its text into a sink (the address of an al_out), as print writes it.
     */
    private Consumer<String> text(Expr e) {
        if (e instanceof Call c && c.asText) return format(c);
        String v = lowerLvalue(e);
        return sink -> emit(fmtStmt(e.type, sink, v, "0"));
    }

    /**
     * Lowers the operands of fixed, pad_left or pad_right and checks their range now, before anything is
     * written, as the interpreter evaluates them; returns what writes the text into a sink. Padding measures
     * the text first by writing it into a sink that only counts.
     */
    private Consumer<String> format(Call c) {
        List<Arg> args = c.args;
        String at = loc(c.span);
        if (c.builtin == Builtin.FIXED) {
            String x = tmp(Type.F64, "(double)(" + lower(args.get(0).expr()) + ")");
            Type dt = args.get(1).expr().type;
            String d = tmp(dt, lower(args.get(1).expr()));
            boolean signed = Type.kind(dt).signed;
            rangeTrap((signed ? "(" + d + ") < 0 || " : "") + "(" + d + ") > " + Format.MAX_DECIMALS + (signed ? "" : "u"),
                "fixed() needs 0 to " + Format.MAX_DECIMALS + " decimals, found ", dt, d, at);
            return sink -> emit("al_fmt_fixed(" + sink + ", " + x + ", (int64_t)(" + d + "));");
        }
        Consumer<String> value = text(args.get(0).expr());
        Type wt = args.get(1).expr().type;
        String w = tmp(wt, lower(args.get(1).expr()));
        String fill = tmp(Type.U8, lower(args.get(2).expr()));
        PrimKind wk = Type.kind(wt);
        // An i8, u8, i16 or u16 is never too wide, and C compilers reject a comparison that is always false.
        if (wk.bits > 16) {
            rangeTrap("(" + w + ") > " + Format.MAX_PAD + (wk.signed ? "" : "u"),
                c.name + "() width must be at most " + Format.MAX_PAD + ", found ", wt, w, at);
        }
        boolean left = c.builtin == Builtin.PAD_LEFT;
        return sink -> {
            String m = "al_m" + ++tmpCount;
            open("{");
            emit("al_out " + m + " = {0, 0, 0u, 0u};");
            value.accept("&" + m);
            String pad = "al_pad(" + sink + ", " + fill + ", (int64_t)(" + w + "), " + m + ".len);";
            if (left) emit(pad);
            value.accept(sink);
            if (!left) emit(pad);
            close("}");
        };
    }

    /** Traps (R0013) when {@code cond} holds, with {@code message} and then the value {@code v} of type {@code t}. */
    private void rangeTrap(String cond, String message, Type t, String v, String at) {
        open("if (" + cond + ") {");
        emit("al_out al_e = al_trap_begin(\"R0013\");");
        emit("AL_PUTS(&al_e, " + cString(utf8(message)) + ");");
        emit(fmtStmt(t, "&al_e", v, "0"));
        emit("al_trap_end(&al_e, " + at + ");");
        close("}");
    }

    private String binary(Binary b) {
        if (b.op.isLogic()) {
            String l = lower(b.left);
            String t = "t" + ++tmpCount;
            emit("bool " + t + " = " + l + ";");
            open("if (" + (b.op == BinOp.AND ? t : "!" + t) + ") {");
            String r = lower(b.right);
            emit(t + " = " + r + ";");
            close("}");
            return t;
        }
        if (b.op.isEquality() || b.op.isOrdering()) {
            String l = lower(b.left);
            String r = lower(b.right);
            return tmp(Type.BOOL, compare(b, l, r));
        }
        String l = lower(b.left);
        String lt = Type.kind(b.left.type).isFloat ? l : tmp(b.left.type, l);
        String r = lower(b.right);
        String v = arith(b.op, Type.kind(b.left.type), Type.kind(b.right.type), lt, r, b.span);
        return tmp(b.type, v);
    }

    private String compare(Binary b, String l, String r) {
        if (b.op.isEquality()) {
            String eq = eqExpr(b.left.type, b.right.type, l, r);
            return b.op == BinOp.EQ ? eq : "(!" + eq + ")";
        }
        if (b.left.type instanceof Type.Str) return "(" + cmpExpr(b.left.type, l, r) + " " + b.op.text + " 0)";
        return "((" + l + ") " + b.op.text + " (" + r + "))";
    }

    private String arith(BinOp op, PrimKind k, PrimKind rk, String l, String r, Span at) {
        if (k.isFloat) {
            String t = cPrim(k);
            return "((" + t + ")((" + l + ") " + op.text + " (" + r + ")))";
        }
        String n = k.name;
        return switch (op) {
            case ADD -> "al_add_" + n + "(" + l + ", " + r + ", " + loc(at) + ")";
            case SUB -> "al_sub_" + n + "(" + l + ", " + r + ", " + loc(at) + ")";
            case MUL -> "al_mul_" + n + "(" + l + ", " + r + ", " + loc(at) + ")";
            case DIV -> "al_div_" + n + "(" + l + ", " + r + ", " + loc(at) + ")";
            case MOD -> "al_rem_" + n + "(" + l + ", " + r + ", " + loc(at) + ")";
            case BAND, BOR, BXOR -> "((" + cPrim(k) + ")((" + l + ") " + op.text + " (" + r + ")))";
            case SHL, SHR -> {
                String amount = rk.signed
                    ? "al_shamt_s((int64_t)(" + r + "), " + k.bits + ", \"" + n + "\", " + loc(at) + ")"
                    : "al_shamt_u((uint64_t)(" + r + "), " + k.bits + ", \"" + n + "\", " + loc(at) + ")";
                yield "al_" + (op == BinOp.SHL ? "shl_" : "shr_") + n + "(" + l + ", " + amount + ")";
            }
            default -> throw new IllegalStateException(op.name());
        };
    }

    /** `str[N](s)` or `list[T; N](xs)`: R0004 if the value is longer than N, else a copy with capacity N. */
    private String resize(Resize r) {
        String v = lowerLvalue(r.arg);
        boolean str = r.type instanceof Type.Str;
        int cap = str ? ((Type.Str) r.type).cap() : ((Type.ListT) r.type).cap();
        emit("if ((" + v + ").len > " + cap + "u) al_resize_trap(" + (str ? 1 : 0) + ", (" + v + ").len, "
            + cString(utf8(r.type.toString())) + ", " + loc(r.span) + ");");
        return coerce(v, r.arg.type, r.type);
    }

    private String convert(Convert c) {
        PrimKind from = Type.kind(c.arg.type);
        PrimKind to = c.target;
        if (c.arg.type instanceof Type.Str && to.isFloat) {
            String s = lowerLvalue(c.arg);
            return tmp(Type.F64, "al_str_to_f64((" + s + ").b, (" + s + ").len, " + loc(c.span) + ")");
        }
        if (c.arg.type instanceof Type.Str) {
            String s = lowerLvalue(c.arg);
            String max = "(uint64_t)" + (to.signed ? "INT" : "UINT") + to.bits + "_MAX";
            return tmp(Type.prim(to), "(" + cPrim(to) + ")" + (to.signed ? "al_str_to_s(" : "al_str_to_u(") + "(" + s + ").b, ("
                + s + ").len, " + max + ", \"" + to.name + "\", " + loc(c.span) + ")");
        }
        String v = lower(c.arg);
        if (from == to) return v;
        String at = loc(c.span);
        // Every conversion goes into a temporary, so nested conversions stay flat in C (see Unary in lower).
        Type t = Type.prim(to);
        if (from == PrimKind.BOOL) return tmp(t, "(" + cPrim(to) + ")((" + v + ") ? 1 : 0)");
        if (from.isFloat) {
            if (to == PrimKind.F64) return tmp(t, "(double)(" + v + ")");
            if (to == PrimKind.F32) return tmp(t, "(float)(" + v + ")");
            return tmp(t, "al_from_f_" + to.name + "((double)(" + v + "), " + at + ")");
        }
        if (to.isFloat) {
            if (from == PrimKind.U64) return tmp(t, (to == PrimKind.F64 ? "al_u64_to_f64(" : "al_u64_to_f32(") + v + ")");
            return tmp(t, "(" + cPrim(to) + ")(int64_t)(" + v + ")");
        }
        String carrier = from.signed ? "al_from_s_" + to.name + "((int64_t)(" : "al_from_u_" + to.name + "((uint64_t)(";
        return tmp(t, carrier + v + "), " + at + ")");
    }

    private String builtin(Call c) {
        List<Arg> args = c.args;
        String at = loc(c.span);
        switch (c.builtin) {
            case PRINT -> {
                List<Consumer<String>> vals = new ArrayList<>();
                for (Arg a : args) vals.add(text(a.expr()));
                open("{");
                emit("al_out al_o = al_stdout_sink();");
                for (Consumer<String> v : vals) v.accept("&al_o");
                emit("AL_PUTS(&al_o, \"\\n\");");
                close("}");
                return null;
            }
            case LEN -> {
                Type t = args.get(0).expr().type;
                String v = lower(args.get(0).expr());
                if (t instanceof Type.ArrayT a) return "INT64_C(" + a.len() + ")";
                return "((int64_t)(" + v + ").len)";
            }
            case CAP -> {
                Type t = args.get(0).expr().type;
                lower(args.get(0).expr());
                int cap = switch (t) {
                    case Type.Str s -> s.cap();
                    case Type.MapT m -> m.cap();
                    case Type.SetT s -> s.cap();
                    default -> ((Type.ListT) t).cap();
                };
                return "INT64_C(" + cap + ")";
            }
            case PUSH -> {
                Type t = args.get(0).expr().type;
                String place = lower(args.get(0).expr());
                Type elem = Type.elementOf(t);
                String v = coerce(lower(args.get(1).expr()), args.get(1).expr().type, elem);
                // The value cannot refer to the target (E0208), so an aggregate is stored from where it is.
                String vt = Type.isAggregate(elem) ? v : tmp(elem, v);
                int cap = t instanceof Type.Str s ? s.cap() : ((Type.ListT) t).cap();
                String kind = t instanceof Type.Str ? "str" : "list";
                emit("if ((" + place + ").len >= " + cap + "u) AL_TRAP(\"R0004\", \"push to a full " + kind + " (capacity " + cap + ")\", " + at + ");");
                emit("(" + place + ")." + (t instanceof Type.Str ? "b" : "v") + "[(" + place + ").len++] = " + vt + ";");
                return null;
            }
            case POP -> {
                Type t = args.get(0).expr().type;
                String place = lower(args.get(0).expr());
                String kind = t instanceof Type.Str ? "str" : "list";
                emit("if ((" + place + ").len == 0) AL_TRAP(\"R0012\", \"pop from an empty " + kind + "\", " + at + ");");
                return tmp(Type.elementOf(t), "(" + place + ")." + (t instanceof Type.Str ? "b" : "v") + "[--(" + place + ").len]");
            }
            case CLEAR -> {
                String place = lower(args.get(0).expr());
                emit("(" + place + ").len = 0;");
                return null;
            }
            case APPEND -> {
                Type st = args.get(0).expr().type;
                int cap = ((Type.Str) st).cap();
                String place = lower(args.get(0).expr());
                List<Consumer<String>> vals = new ArrayList<>();
                for (int i = 1; i < args.size(); i++) vals.add(text(args.get(i).expr()));
                open("{");
                String sp = "t" + ++tmpCount;
                emit(ct(st) + " *" + sp + " = &(" + place + ");");
                for (int i = 0; i < vals.size(); i++) {
                    open("{");
                    emit("uint32_t al_before = " + sp + "->len;");
                    emit("al_out al_o = {0, " + sp + "->b, " + cap + "u, " + sp + "->len};");
                    vals.get(i).accept("&al_o");
                    open("if (al_o.len > " + cap + "u) {");
                    emit("al_out al_e = al_trap_begin(\"R0004\");");
                    emit("AL_PUTS(&al_e, \"append exceeds str capacity " + cap + " (length \");");
                    emit("al_fmt_u64(&al_e, al_before);");
                    emit("AL_PUTS(&al_e, \", appending \");");
                    emit("al_fmt_u64(&al_e, al_o.len - al_before);");
                    emit("AL_PUTS(&al_e, \" bytes)\");");
                    emit("al_trap_end(&al_e, " + at + ");");
                    close("}");
                    emit(sp + "->len = al_o.len;");
                    close("}");
                }
                close("}");
                return null;
            }
            case ABS -> {
                PrimKind k = Type.kind(c.type);
                String v = tmp(c.type, lower(args.get(0).expr()));
                if (k.isFloat) return "((" + cPrim(k) + ")fabs(" + v + "))";
                return tmp(c.type, "al_abs_" + k.name + "(" + v + ", " + at + ")");
            }
            case MIN, MAX -> {
                String a = tmp(c.type, lower(args.get(0).expr()));
                String b = tmp(c.type, lower(args.get(1).expr()));
                String op = c.builtin == Builtin.MIN ? "<" : ">";
                return "(" + b + " " + op + " " + a + " ? " + b + " : " + a + ")";
            }
            case SQRT, FLOOR, CEIL -> {
                PrimKind k = Type.kind(c.type);
                String v = lower(args.get(0).expr());
                String name = c.builtin.name + (k == PrimKind.F32 ? "f" : "");
                return "((" + cPrim(k) + ")" + name + "(" + v + "))";
            }
            case EXP, LOG, LOG2, LOG10, SIN, COS, TAN, ASIN, ACOS, ATAN -> {
                PrimKind k = Type.kind(c.type);
                String v = lower(args.get(0).expr());
                return tmp(c.type, "(" + cPrim(k) + ")al_m_" + c.builtin.name + "((double)(" + v + "))");
            }
            case ATAN2 -> {
                PrimKind k = Type.kind(c.type);
                String y = tmp(c.type, lower(args.get(0).expr()));
                String x = tmp(c.type, lower(args.get(1).expr()));
                return tmp(c.type, "(" + cPrim(k) + ")al_m_atan2((double)" + y + ", (double)" + x + ")");
            }
            case ROUND, TRUNC -> {
                PrimKind k = Type.kind(c.type);
                String v = lower(args.get(0).expr());
                return tmp(c.type, "(" + cPrim(k) + ")al_" + c.builtin.name + "((double)(" + v + "))");
            }
            case IS_NAN, IS_FINITE -> {
                String v = tmp(args.get(0).expr().type, lower(args.get(0).expr()));
                return tmp(Type.BOOL, (c.builtin == Builtin.IS_NAN ? "isnan(" : "isfinite(") + v + ") != 0");
            }
            case CLAMP -> {
                String x = tmp(c.type, lower(args.get(0).expr()));
                String lo = tmp(c.type, lower(args.get(1).expr()));
                String hi = tmp(c.type, lower(args.get(2).expr()));
                open("if (!(" + lo + " <= " + hi + ")) {");
                emit("al_out al_e = al_trap_begin(\"R0013\");");
                emit("AL_PUTS(&al_e, \"clamp needs lo <= hi, found lo \");");
                emit(fmtStmt(c.type, "&al_e", lo, "0"));
                emit("AL_PUTS(&al_e, \" and hi \");");
                emit(fmtStmt(c.type, "&al_e", hi, "0"));
                emit("al_trap_end(&al_e, " + at + ");");
                close("}");
                return tmp(c.type, x + " < " + lo + " ? " + lo + " : (" + x + " > " + hi + " ? " + hi + " : " + x + ")");
            }
            case POW -> {
                PrimKind k = Type.kind(c.type);
                if (k.isFloat) {
                    String x = tmp(c.type, lower(args.get(0).expr()));
                    String n = tmp(c.type, lower(args.get(1).expr()));
                    return tmp(c.type, "(" + cPrim(k) + ")al_m_pow((double)" + x + ", (double)" + n + ")");
                }
                String x = tmp(c.type, lower(args.get(0).expr()));
                PrimKind nk = Type.kind(args.get(1).expr().type);
                String n = lower(args.get(1).expr());
                String exp = tmp(Type.U64, nk.signed ? "al_pow_exp((int64_t)(" + n + "), " + at + ")" : "(uint64_t)(" + n + ")");
                String call = k.signed
                    ? "al_pow_s((int64_t)" + x + ", " + exp + ", INT" + k.bits + "_MIN, INT" + k.bits + "_MAX"
                    : "al_pow_u((uint64_t)" + x + ", " + exp + ", UINT" + k.bits + "_MAX";
                return tmp(c.type, "(" + cPrim(k) + ")" + call + ", \"" + k.name + "\", " + at + ")");
            }
            case GCD, LCM -> {
                PrimKind k = Type.kind(c.type);
                String a = tmp(c.type, lower(args.get(0).expr()));
                String b = tmp(c.type, lower(args.get(1).expr()));
                String ma = k.signed ? "al_mag((int64_t)" + a + ")" : "(uint64_t)" + a;
                String mb = k.signed ? "al_mag((int64_t)" + b + ")" : "(uint64_t)" + b;
                String hi = "(uint64_t)" + (k.signed ? "INT" : "UINT") + k.bits + "_MAX";
                return tmp(c.type, "(" + cPrim(k) + ")al_" + c.builtin.name + "(" + ma + ", " + mb + ", " + hi + ", \""
                    + k.name + "\", " + at + ")");
            }
            case WRAPPING_ADD, WRAPPING_SUB, WRAPPING_MUL, SATURATING_ADD, SATURATING_SUB, SATURATING_MUL -> {
                PrimKind k = Type.kind(c.type);
                String a = tmp(c.type, lower(args.get(0).expr()));
                String b = tmp(c.type, lower(args.get(1).expr()));
                int op = switch (c.builtin) {
                    case WRAPPING_ADD, SATURATING_ADD -> 0;
                    case WRAPPING_SUB, SATURATING_SUB -> 1;
                    default -> 2;
                };
                boolean wrap = c.builtin.name.startsWith("wrapping");
                String s = k.signed ? "(int64_t)" : "";
                if (wrap) {
                    String r = "al_wrapping((uint64_t)" + s + a + ", (uint64_t)" + s + b + ", " + op + ")";
                    return tmp(c.type, k.signed ? "al_wrap_" + k.name + "((uint" + k.bits + "_t)" + r + ")" : "(" + cPrim(k) + ")" + r);
                }
                return tmp(c.type, "(" + cPrim(k) + ")" + (k.signed
                    ? "al_sat_s((int64_t)" + a + ", (int64_t)" + b + ", " + op + ", INT" + k.bits + "_MIN, INT" + k.bits + "_MAX)"
                    : "al_sat_u((uint64_t)" + a + ", (uint64_t)" + b + ", " + op + ", UINT" + k.bits + "_MAX)"));
            }
            case IS_DIGIT, IS_ALPHA, IS_ALNUM, IS_SPACE, IS_UPPER, IS_LOWER -> {
                String ch = tmp(Type.U8, lower(args.get(0).expr()));
                String digit = "(" + ch + " >= 48 && " + ch + " <= 57)";
                String upper = "(" + ch + " >= 65 && " + ch + " <= 90)";
                String lowerCase = "(" + ch + " >= 97 && " + ch + " <= 122)";
                return tmp(Type.BOOL, switch (c.builtin) {
                    case IS_DIGIT -> digit;
                    case IS_ALPHA -> upper + " || " + lowerCase;
                    case IS_ALNUM -> upper + " || " + lowerCase + " || " + digit;
                    case IS_SPACE -> "al_is_space(" + ch + ") != 0";
                    case IS_UPPER -> upper;
                    default -> lowerCase;
                });
            }
            case TO_UPPER, TO_LOWER -> {
                boolean up = c.builtin == Builtin.TO_UPPER;
                Expr a = args.get(0).expr();
                if (a.type instanceof Type.Str) {
                    String v = lowerLvalue(a);
                    String r = tmp(c.type, "{0}");
                    emit(r + ".len = al_case_into(" + r + ".b, (" + v + ").b, (" + v + ").len, " + (up ? 1 : 0) + ");");
                    return r;
                }
                String ch = tmp(Type.U8, lower(a));
                return tmp(Type.U8, up ? "(uint8_t)(" + ch + " >= 97 && " + ch + " <= 122 ? " + ch + " - 32 : " + ch + ")"
                    : "(uint8_t)(" + ch + " >= 65 && " + ch + " <= 90 ? " + ch + " + 32 : " + ch + ")");
            }
            case COUNT -> {
                Expr xs = args.get(0).expr();
                String h = lowerLvalue(xs);
                if (xs.type instanceof Type.Str) {
                    String[] p = pattern(args.get(1).expr());
                    return tmp(Type.I64, "al_count_bytes((" + h + ").b, (" + h + ").len, " + p[0] + ", " + p[1] + ", " + at + ")");
                }
                Expr needle = args.get(1).expr();
                String x = lowerLvalue(needle);
                Type elem = Type.elementOf(xs.type);
                String n = xs.type instanceof Type.ArrayT arr ? arr.len() + "u" : "(" + h + ").len";
                String k = tmp(Type.I64, "0");
                String i = "t" + ++tmpCount;
                open("{");
                emit("uint32_t " + i + ";");
                open("for (" + i + " = 0; " + i + " < " + n + "; " + i + "++) {");
                emit("if (" + eqExpr(elem, needle.type, "(" + h + ").v[" + i + "]", x) + " != 0) " + k + "++;");
                close("}");
                close("}");
                return k;
            }
            case CONTAINS, INDEX_OF -> {
                Expr xs = args.get(0).expr();
                if (xs.type instanceof Type.MapT || xs.type instanceof Type.SetT) {
                    Type kt = xs.type instanceof Type.MapT mt ? mt.key() : ((Type.SetT) xs.type).elem();
                    String h = lowerLvalue(xs);
                    String key = keyLvalue(args.get(1).expr(), kt);
                    String found = "t" + ++tmpCount;
                    emit("int " + found + ";");
                    emit("(void)al_find_" + keyedFns(xs.type) + "(&(" + h + "), &" + key + ", &" + found + ");");
                    return tmp(Type.BOOL, found + " != 0");
                }
                String h = lowerLvalue(xs);
                String at0;
                if (xs.type instanceof Type.Str) {
                    String[] p = pattern(args.get(1).expr());
                    at0 = tmp(Type.I64, "al_find_bytes((" + h + ").b, (" + h + ").len, " + p[0] + ", " + p[1] + ", 0)");
                } else {
                    Expr needle = args.get(1).expr();
                    String x = lowerLvalue(needle);
                    Type elem = Type.elementOf(xs.type);
                    String n = xs.type instanceof Type.ArrayT arr ? arr.len() + "u" : "(" + h + ").len";
                    at0 = tmp(Type.I64, "-1");
                    String i = "t" + ++tmpCount;
                    open("{");
                    emit("uint32_t " + i + ";");
                    open("for (" + i + " = 0; " + i + " < " + n + "; " + i + "++) {");
                    open("if (" + eqExpr(elem, needle.type, "(" + h + ").v[" + i + "]", x) + " != 0) {");
                    emit(at0 + " = (int64_t)" + i + ";");
                    emit("break;");
                    close("}");
                    close("}");
                    close("}");
                }
                return c.builtin == Builtin.CONTAINS ? tmp(Type.BOOL, at0 + " >= 0") : at0;
            }
            case STARTS_WITH, ENDS_WITH -> {
                String v = lowerLvalue(args.get(0).expr());
                String[] p = pattern(args.get(1).expr());
                String fn = c.builtin == Builtin.STARTS_WITH ? "al_starts_with" : "al_ends_with";
                return tmp(Type.BOOL, fn + "((" + v + ").b, (" + v + ").len, " + p[0] + ", " + p[1] + ")");
            }
            case SLICE -> {
                Type t = args.get(0).expr().type;
                String v = lowerLvalue(args.get(0).expr());
                String from = position(args.get(1).expr());
                String to = position(args.get(2).expr());
                String len = t instanceof Type.ArrayT arr ? arr.len() + "u" : "(" + v + ").len";
                String f = tmp(Type.U32, "0");
                String n = tmp(Type.U32, "al_slice(" + from + ", " + to + ", " + len + ", &" + f + ", " + at + ")");
                String r = tmp(c.type, "{0}");
                if (t instanceof Type.Str) {
                    emit(r + ".len = al_copy_bytes(" + r + ".b, (" + v + ").b + " + f + ", " + n + ");");
                } else {
                    String i = "t" + ++tmpCount;
                    open("{");
                    emit("uint32_t " + i + ";");
                    emit("for (" + i + " = 0; " + i + " < " + n + "; " + i + "++) " + r + ".v[" + i + "] = (" + v + ").v[" + f + " + " + i + "];");
                    close("}");
                    emit(r + ".len = " + n + ";");
                }
                return r;
            }
            case TRIM -> {
                String v = lowerLvalue(args.get(0).expr());
                String r = tmp(c.type, "{0}");
                emit(r + ".len = al_trim_into(" + r + ".b, (" + v + ").b, (" + v + ").len);");
                return r;
            }
            case FIXED, PAD_LEFT, PAD_RIGHT -> {
                // Stored in a str: the text is written into it, and must fit.
                String target = into;
                into = null;
                Consumer<String> w = format(c);
                int cap = ((Type.Str) c.type).cap();
                String r = dest(c.type, target);
                open("{");
                emit("al_out al_o = {0, " + r + ".b, " + cap + "u, 0u};");
                w.accept("&al_o");
                emit("if (al_o.len > " + cap + "u) al_need_trap(\"" + c.name + "\", al_o.len, " + cap + "u, " + at + ");");
                emit(r + ".len = al_o.len;");
                close("}");
                return r;
            }
            case IS_INT, IS_FLOAT -> {
                String v = lowerLvalue(args.get(0).expr());
                return tmp(Type.BOOL, (c.builtin == Builtin.IS_INT ? "al_is_int((" : "al_is_float((") + v + ").b, (" + v + ").len)");
            }
            case SPLIT, WORDS -> {
                String target = into;
                into = null;
                String v = lowerLvalue(args.get(0).expr());
                boolean words = c.builtin == Builtin.WORDS;
                String[] p = words ? new String[] {"0", "0u"} : pattern(args.get(1).expr());
                String r = dest(c.type, target);
                emit("(void)" + splitFn((Type.ListT) c.type) + "(&" + r + ", (" + v + ").b, (" + v + ").len, " + p[0] + ", " + p[1]
                    + ", " + (words ? 1 : 0) + ", 0, " + at + ");");
                return r;
            }
            case IS_UTF8, CHAR_COUNT -> {
                String v = lowerLvalue(args.get(0).expr());
                return c.builtin == Builtin.IS_UTF8 ? tmp(Type.BOOL, "al_is_utf8((" + v + ").b, (" + v + ").len)")
                    : tmp(Type.I64, "al_char_count((" + v + ").b, (" + v + ").len)");
            }
            case CHARS -> {
                String target = into;
                into = null;
                String v = lowerLvalue(args.get(0).expr());
                String r = dest(c.type, target);
                emit(charsFn((Type.ListT) c.type) + "(&" + r + ", (" + v + ").b, (" + v + ").len, " + at + ");");
                return r;
            }
            case PUSH_CHAR -> {
                Type st = args.get(0).expr().type;
                String place = lower(args.get(0).expr());
                String cp = position(args.get(1).expr());
                emit("al_push_char((" + place + ").b, &(" + place + ").len, " + ((Type.Str) st).cap() + "u, " + cp + ", " + at + ");");
                return null;
            }
            case SLICE_CHARS -> {
                String v = lowerLvalue(args.get(0).expr());
                String from = position(args.get(1).expr());
                String to = position(args.get(2).expr());
                String r = tmp(c.type, "{0}");
                emit(r + ".len = al_slice_chars(" + r + ".b, (" + v + ").b, (" + v + ").len, " + from + ", " + to + ", " + at + ");");
                return r;
            }
            case TRY_SPLIT, TRY_WORDS -> {
                Type.ListT lt = (Type.ListT) args.get(0).expr().type;
                String place = lower(args.get(0).expr());
                String v = lowerLvalue(args.get(1).expr());
                boolean words = c.builtin == Builtin.TRY_WORDS;
                String[] p = words ? new String[] {"0", "0u"} : pattern(args.get(2).expr());
                return tmp(Type.BOOL, "(bool)" + splitFn(lt) + "(&(" + place + "), (" + v + ").b, (" + v + ").len, " + p[0] + ", "
                    + p[1] + ", " + (words ? 1 : 0) + ", 1, " + at + ")");
            }
            case JOIN -> {
                String target = into;
                into = null;
                Type pt = args.get(0).expr().type;
                String parts = lowerLvalue(args.get(0).expr());
                String[] p = pattern(args.get(1).expr());
                String r = dest(c.type, target);
                emit(joinFn((Type.Str) c.type, pt) + "(&" + r + ", &(" + parts + "), " + p[0] + ", " + p[1] + ", " + at + ");");
                return r;
            }
            case REPLACE -> {
                String target = into;
                into = null;
                String v = lowerLvalue(args.get(0).expr());
                String[] f = pattern(args.get(1).expr());
                String[] t = pattern(args.get(2).expr());
                String r = dest(c.type, target);
                emit(r + ".len = al_replace_into(" + r + ".b, " + ((Type.Str) c.type).cap() + "u, (" + v + ").b, (" + v + ").len, "
                    + f[0] + ", " + f[1] + ", " + t[0] + ", " + t[1] + ", " + at + ");");
                return r;
            }
            case SORT, REVERSE -> {
                Type t = args.get(0).expr().type;
                String place = lower(args.get(0).expr());
                String base = "(" + place + ")." + (t instanceof Type.Str ? "b" : "v");
                String n = t instanceof Type.ArrayT arr ? arr.len() + "u" : "(" + place + ").len";
                String size = "sizeof " + base + "[0]";
                if (c.builtin == Builtin.REVERSE) emit("al_reverse(" + base + ", " + n + ", " + size + ");");
                else emit("al_heapsort(" + base + ", " + n + ", " + size + ", " + ordFn(Type.elementOf(t)) + ");");
                return null;
            }
            case INSERT -> {
                Type t = args.get(0).expr().type;
                if (t instanceof Type.MapT mt) {
                    String place = lower(args.get(0).expr());
                    String key = keyLvalue(args.get(1).expr(), mt.key());
                    String val = keyLvalue(args.get(2).expr(), mt.value());
                    emit("*al_put_" + keyedFns(mt) + "(&(" + place + "), &" + key + ", " + at + ") = " + val + ";");
                    return null;
                }
                if (t instanceof Type.SetT st) {
                    String place = lower(args.get(0).expr());
                    String key = keyLvalue(args.get(1).expr(), st.elem());
                    emit("al_ins_" + keyedFns(st) + "(&(" + place + "), &" + key + ", " + at + ");");
                    return null;
                }
                String place = lower(args.get(0).expr());
                String pos = position(args.get(1).expr());
                Type elem = Type.elementOf(t);
                String v = coerce(lower(args.get(2).expr()), args.get(2).expr().type, elem);
                // As in push, the value cannot refer to the target (E0208), so an aggregate is stored from where it is.
                String vt = Type.isAggregate(elem) ? v : tmp(elem, v);
                int cap = t instanceof Type.Str s ? s.cap() : ((Type.ListT) t).cap();
                String kind = t instanceof Type.Str ? "str" : "list";
                String arr = "(" + place + ")." + (t instanceof Type.Str ? "b" : "v");
                String i = tmp(Type.U32, "al_insert_pos(" + pos + ", (" + place + ").len, " + at + ")");
                emit("if ((" + place + ").len >= " + cap + "u) AL_TRAP(\"R0004\", \"insert into a full " + kind + " (capacity " + cap + ")\", " + at + ");");
                String k = "t" + ++tmpCount;
                open("{");
                emit("uint32_t " + k + ";");
                emit("for (" + k + " = (" + place + ").len; " + k + " > " + i + "; " + k + "--) " + arr + "[" + k + "] = " + arr + "[" + k + " - 1];");
                close("}");
                emit(arr + "[" + i + "] = " + vt + ";");
                emit("(" + place + ").len++;");
                return null;
            }
            case REMOVE -> {
                Type t = args.get(0).expr().type;
                if (t instanceof Type.MapT || t instanceof Type.SetT) {
                    Type kt = t instanceof Type.MapT mt ? mt.key() : ((Type.SetT) t).elem();
                    String place = lower(args.get(0).expr());
                    String key = keyLvalue(args.get(1).expr(), kt);
                    return tmp(Type.BOOL, "al_del_" + keyedFns(t) + "(&(" + place + "), &" + key + ")");
                }
                String place = lower(args.get(0).expr());
                Expr ie = args.get(1).expr();
                String idx = lower(ie);
                String check = Type.kind(ie.type).signed ? "al_idx_s((int64_t)(" + idx + "), (" + place + ").len, " + at + ")"
                    : "al_idx_u((uint64_t)(" + idx + "), (" + place + ").len, " + at + ")";
                String i = tmp(Type.U32, check);
                String arr = "(" + place + ")." + (t instanceof Type.Str ? "b" : "v");
                String r = tmp(Type.elementOf(t), arr + "[" + i + "]");
                String k = "t" + ++tmpCount;
                open("{");
                emit("uint32_t " + k + ";");
                emit("for (" + k + " = " + i + "; " + k + " + 1 < (" + place + ").len; " + k + "++) " + arr + "[" + k + "] = " + arr + "[" + k + " + 1];");
                close("}");
                emit("(" + place + ").len--;");
                return r;
            }
            case COMPARE -> {
                Type t = args.get(0).expr().type;
                String a = lowerLvalue(args.get(0).expr());
                String b = lowerLvalue(args.get(1).expr());
                String cmp = tmp(Type.I32, "(int32_t)(" + cmpExpr(t, a, b) + ")");
                return tmp(Type.I64, "(int64_t)((" + cmp + " > 0) - (" + cmp + " < 0))");
            }
            case GET_OR -> {
                Type.MapT mt = (Type.MapT) args.get(0).expr().type;
                String m = lowerLvalue(args.get(0).expr());
                String key = keyLvalue(args.get(1).expr(), mt.key());
                String d = keyLvalue(args.get(2).expr(), mt.value());
                String found = "t" + ++tmpCount;
                String i = "t" + ++tmpCount;
                emit("int " + found + ";");
                emit("uint32_t " + i + " = al_find_" + keyedFns(mt) + "(&(" + m + "), &" + key + ", &" + found + ");");
                return tmp(mt.value(), found + " ? (" + m + ").v[" + i + "] : " + d);
            }
            case PANIC -> {
                String v = lowerLvalue(args.get(0).expr());
                open("{");
                emit("al_out al_e = al_trap_begin(\"R0010\");");
                emit("AL_PUTS(&al_e, \"panic: \");");
                emit("al_fmt_str(&al_e, (" + v + ").b, (" + v + ").len, 0);");
                emit("al_trap_end(&al_e, " + at + ");");
                close("}");
                return null;
            }
        }
        throw new IllegalStateException();
    }

    // =================================================================== standard library helpers

    /** A str or a u8 byte as a C pointer and length: the str's bytes, or the byte in a temporary. */
    private String[] pattern(Expr e) {
        if (e.type instanceof Type.Str) return strPattern(lowerLvalue(e));
        String t = tmp(Type.U8, lower(e));
        return new String[] {"&" + t, "1u"};
    }

    /** A pattern str whose value is in the lvalue v. */
    private static String[] strPattern(String v) {
        return new String[] {"(" + v + ").b", "(" + v + ").len"};
    }

    /** A position argument of any integer type, as an al_pos in a temporary. */
    private String position(Expr e) {
        String v = lower(e);
        String p = "t" + ++tmpCount;
        emit("al_pos " + p + " = " + (Type.kind(e.type).signed ? "al_pos_s((int64_t)(" : "al_pos_u((uint64_t)(") + v + "));");
        return p;
    }

    /** A C expression ordering lvalues a and b of type t as sort does: negative, zero or positive. */
    private String cmpExpr(Type t, String a, String b) {
        return switch (t) {
            case Type.Prim p -> p.kind().isFloat ? "al_cmp_f64((double)(" + a + "), (double)(" + b + "))"
                : "(((" + a + ") > (" + b + ")) - ((" + a + ") < (" + b + ")))";
            case Type.Str s -> "al_cmp_bytes((" + a + ").b, (" + a + ").len, (" + b + ").b, (" + b + ").len)";
            default -> ordFn(t) + "(&(" + a + "), &(" + b + "))";
        };
    }

    /** The comparison function of sort for elements of type t, with the signature al_heapsort takes. */
    private String ordFn(Type t) {
        String name = "al_ord_" + mangle(t);
        if (!doneHelpers.add(name)) return name;
        String ty = ct(t);
        StringBuilder body = new StringBuilder();
        body.append("    const ").append(ty).append(" *a = (const ").append(ty).append(" *)pa;\n");
        body.append("    const ").append(ty).append(" *b = (const ").append(ty).append(" *)pb;\n");
        switch (t) {
            case Type.Prim p -> body.append("    return ").append(cmpExpr(t, "*a", "*b")).append(";\n");
            case Type.Str s -> body.append("    return ").append(cmpExpr(t, "*a", "*b")).append(";\n");
            case Type.ArrayT arr -> body.append("    uint32_t i;\n    for (i = 0; i < ").append(arr.len()).append("u; i++) {\n")
                .append("        int c = ").append(cmpExpr(arr.elem(), "a->v[i]", "b->v[i]")).append(";\n")
                .append("        if (c != 0) return c;\n    }\n    return 0;\n");
            case Type.ListT l -> body.append("    uint32_t i;\n    for (i = 0; i < a->len && i < b->len; i++) {\n")
                .append("        int c = ").append(cmpExpr(l.elem(), "a->v[i]", "b->v[i]")).append(";\n")
                .append("        if (c != 0) return c;\n    }\n    return (a->len > b->len) - (a->len < b->len);\n");
            case Type.StructT st -> {
                body.append("    int c;\n");
                for (Field f : st.decl().fields) {
                    body.append("    c = ").append(cmpExpr(f.type, "a->f_" + f.name, "b->f_" + f.name)).append(";\n")
                        .append("    if (c != 0) return c;\n");
                }
                body.append("    return 0;\n");
            }
            case Type.SetT st -> body.append("    uint32_t i;\n    for (i = 0; i < a->len && i < b->len; i++) {\n")
                .append("        int c = ").append(cmpExpr(st.elem(), "a->v[i]", "b->v[i]")).append(";\n")
                .append("        if (c != 0) return c;\n    }\n    return (a->len > b->len) - (a->len < b->len);\n");
            case Type.MapT m -> body.append("    uint32_t i;\n    for (i = 0; i < a->len && i < b->len; i++) {\n")
                .append("        int c = ").append(cmpExpr(m.key(), "a->k[i]", "b->k[i]")).append(";\n")
                .append("        if (c == 0) c = ").append(cmpExpr(m.value(), "a->v[i]", "b->v[i]")).append(";\n")
                .append("        if (c != 0) return c;\n    }\n    return (a->len > b->len) - (a->len < b->len);\n");
            case Type.TupleT tt -> {
                body.append("    int c;\n");
                for (int i = 0; i < tt.elems().size(); i++) {
                    body.append("    c = ").append(cmpExpr(tt.elems().get(i), "a->e" + i, "b->e" + i)).append(";\n")
                        .append("    if (c != 0) return c;\n");
                }
                body.append("    return 0;\n");
            }
            case Type.EnumT e -> {
                body.append("    int c = (a->tag > b->tag) - (a->tag < b->tag);\n    if (c != 0) return c;\n");
                for (Variant v : e.decl().variants) {
                    if (v.payload.isEmpty()) continue;
                    body.append("    if (a->tag == ").append(v.index).append("u) {\n");
                    for (int i = 0; i < v.payload.size(); i++) {
                        String f = "u.v_" + v.name + ".p" + i;
                        body.append("        c = ").append(cmpExpr(v.payload.get(i), "a->" + f, "b->" + f)).append(";\n")
                            .append("        if (c != 0) return c;\n");
                    }
                    body.append("    }\n");
                }
                body.append("    return 0;\n");
            }
            default -> throw new IllegalStateException();
        }
        helpers.append("static int ").append(name).append("(const void *pa, const void *pb) {\n").append(body).append("}\n\n");
        return name;
    }

    /** split() and words() into a list of type t: the pieces in turn, each checked for room and then for size. */
    private String splitFn(Type.ListT t) {
        String name = "al_split_" + mangle(t);
        if (!doneHelpers.add(name)) return name;
        int k = ((Type.Str) t.elem()).cap();
        String full = cString(utf8(" makes more than " + t.cap() + " pieces, the capacity of " + t));
        // With try_, a list it does not fit is left empty and 0 returned (try_split, try_words), not a trap.
        helpers.append("static int ").append(name).append("(").append(ct(t)).append(" *r, const uint8_t *s, uint32_t n, ")
            .append("const uint8_t *sep, uint32_t sn, int words, int try_, int line, int col) {\n")
            .append("    uint32_t pos = 0, end;\n")
            .append("    int last = 0;\n")
            .append("    r->len = 0;\n")
            .append("    if (!words && sn == 0) AL_TRAP(\"R0013\", \"split separator is empty\", line, col);\n")
            .append("    for (;;) {\n")
            .append("        if (words) {\n")
            .append("            while (pos < n && al_is_space(s[pos])) pos++;\n")
            .append("            if (pos == n) break;\n")
            .append("            end = pos;\n")
            .append("            while (end < n && !al_is_space(s[end])) end++;\n")
            .append("        } else {\n")
            .append("            int64_t hit = al_find_bytes(s, n, sep, sn, pos);\n")
            .append("            last = hit < 0;\n")
            .append("            end = last ? n : (uint32_t)hit;\n")
            .append("        }\n")
            .append("        if (try_ && (r->len >= ").append(t.cap()).append("u || end - pos > ").append(k).append("u)) {\n")
            .append("            r->len = 0;\n")
            .append("            return 0;\n")
            .append("        }\n")
            .append("        if (r->len >= ").append(t.cap()).append("u) {\n")
            .append("            al_out e = al_trap_begin(\"R0004\");\n")
            .append("            if (words) AL_PUTS(&e, \"words\");\n")
            .append("            else AL_PUTS(&e, \"split\");\n")
            .append("            AL_PUTS(&e, ").append(full).append(");\n")
            .append("            al_trap_end(&e, line, col);\n")
            .append("        }\n")
            .append("        if (end - pos > ").append(k).append("u) al_piece_trap(words, end - pos, ").append(k).append("u, line, col);\n")
            .append("        r->v[r->len].len = al_copy_bytes(r->v[r->len].b, s + pos, end - pos);\n")
            .append("        r->len++;\n")
            .append("        if (words) {\n")
            .append("            pos = end;\n")
            .append("        } else {\n")
            .append("            if (last) break;\n")
            .append("            pos = end + sn;\n")
            .append("        }\n")
            .append("    }\n")
            .append("    return 1;\n")
            .append("}\n\n");
        return name;
    }

    /**
     * The helpers of a map type: find (a binary search, as Stdlib.find), get (R0003 for a missing key), put
     * (adds a new key in its place; R0004 when full) and del. A set has find, ins and del.
     */
    private String keyedFns(Type t) {
        String m = mangle(t);
        String name = "al_kf_" + m;
        if (!doneHelpers.add(name)) return m;
        String ty = ct(t);
        boolean map = t instanceof Type.MapT;
        Type kt = map ? ((Type.MapT) t).key() : ((Type.SetT) t).elem();
        int cap = map ? ((Type.MapT) t).cap() : ((Type.SetT) t).cap();
        String k = ct(kt);
        String keys = map ? "k" : "v";
        StringBuilder sb = new StringBuilder();
        sb.append("static uint32_t al_find_").append(m).append("(const ").append(ty).append(" *m, const ").append(k)
            .append(" *key, int *found) {\n")
            .append("    uint32_t lo = 0, hi = m->len;\n")
            .append("    *found = 0;\n")
            .append("    while (lo < hi) {\n")
            .append("        uint32_t mid = lo + (hi - lo) / 2;\n")
            .append("        int c = ").append(cmpExpr(kt, "m->" + keys + "[mid]", "(*key)")).append(";\n")
            .append("        if (c < 0) lo = mid + 1;\n")
            .append("        else if (c > 0) hi = mid;\n")
            .append("        else {\n            *found = 1;\n            return mid;\n        }\n")
            .append("    }\n")
            .append("    return lo;\n}\n\n");
        String full = cString(utf8("insert into a full " + (map ? "map" : "set") + " (capacity " + cap + ")"));
        if (map) {
            Type vt = ((Type.MapT) t).value();
            String v = ct(vt);
            sb.append("static const ").append(v).append(" *al_get_").append(m).append("(const ").append(ty).append(" *m, const ")
                .append(k).append(" *key, int line, int col) {\n")
                .append("    int found;\n")
                .append("    uint32_t i = al_find_").append(m).append("(m, key, &found);\n")
                .append("    if (!found) {\n")
                .append("        al_out e = al_trap_begin(\"R0003\");\n")
                .append("        AL_PUTS(&e, \"key \");\n")
                .append("        ").append(fmtStmt(kt, "&e", "(*key)", "1")).append("\n")
                .append("        AL_PUTS(&e, \" is not in the map\");\n")
                .append("        al_trap_end(&e, line, col);\n")
                .append("    }\n")
                .append("    return &m->v[i];\n}\n\n");
            sb.append("static ").append(v).append(" *al_put_").append(m).append("(").append(ty).append(" *m, const ").append(k)
                .append(" *key, int line, int col) {\n")
                .append("    int found;\n")
                .append("    uint32_t i = al_find_").append(m).append("(m, key, &found), j;\n")
                .append("    if (found) return &m->v[i];\n")
                .append("    if (m->len >= ").append(cap).append("u) AL_TRAP(\"R0004\", ").append(full).append(", line, col);\n")
                .append("    for (j = m->len; j > i; j--) {\n")
                .append("        m->k[j] = m->k[j - 1];\n")
                .append("        m->v[j] = m->v[j - 1];\n")
                .append("    }\n")
                .append("    m->k[i] = *key;\n")
                .append("    m->len++;\n")
                .append("    return &m->v[i];\n}\n\n");
            sb.append("static bool al_del_").append(m).append("(").append(ty).append(" *m, const ").append(k).append(" *key) {\n")
                .append("    int found;\n")
                .append("    uint32_t i = al_find_").append(m).append("(m, key, &found);\n")
                .append("    if (!found) return false;\n")
                .append("    for (; i + 1 < m->len; i++) {\n")
                .append("        m->k[i] = m->k[i + 1];\n")
                .append("        m->v[i] = m->v[i + 1];\n")
                .append("    }\n")
                .append("    m->len--;\n")
                .append("    return true;\n}\n\n");
        } else {
            sb.append("static void al_ins_").append(m).append("(").append(ty).append(" *m, const ").append(k)
                .append(" *key, int line, int col) {\n")
                .append("    int found;\n")
                .append("    uint32_t i = al_find_").append(m).append("(m, key, &found), j;\n")
                .append("    if (found) return;\n")
                .append("    if (m->len >= ").append(cap).append("u) AL_TRAP(\"R0004\", ").append(full).append(", line, col);\n")
                .append("    for (j = m->len; j > i; j--) m->v[j] = m->v[j - 1];\n")
                .append("    m->v[i] = *key;\n")
                .append("    m->len++;\n}\n\n");
            sb.append("static bool al_del_").append(m).append("(").append(ty).append(" *m, const ").append(k).append(" *key) {\n")
                .append("    int found;\n")
                .append("    uint32_t i = al_find_").append(m).append("(m, key, &found);\n")
                .append("    if (!found) return false;\n")
                .append("    for (; i + 1 < m->len; i++) m->v[i] = m->v[i + 1];\n")
                .append("    m->len--;\n")
                .append("    return true;\n}\n\n");
        }
        helpers.append(sb);
        return m;
    }

    /** chars() into a list of type t: the code points in turn, each checked for room. */
    private String charsFn(Type.ListT t) {
        String name = "al_chars_" + mangle(t);
        if (!doneHelpers.add(name)) return name;
        String full = cString(utf8("chars makes more than " + t.cap() + " code points, the capacity of " + t));
        helpers.append("static void ").append(name).append("(").append(ct(t)).append(" *r, const uint8_t *s, uint32_t n, int line, int col) {\n")
            .append("    uint32_t pos = 0, len;\n")
            .append("    int ok;\n")
            .append("    r->len = 0;\n")
            .append("    while (pos < n) {\n")
            .append("        uint32_t c = al_utf8_next(s, n, pos, &len, &ok);\n")
            .append("        if (r->len >= ").append(t.cap()).append("u) AL_TRAP(\"R0004\", ").append(full).append(", line, col);\n")
            .append("        r->v[r->len++] = c;\n")
            .append("        pos += len;\n")
            .append("    }\n")
            .append("}\n\n");
        return name;
    }

    /** join() of an array or list of str, of type parts, into a str of type t. */
    private String joinFn(Type.Str t, Type parts) {
        String name = "al_join_" + mangle(t) + "_" + mangle(parts);
        if (!doneHelpers.add(name)) return name;
        String n = parts instanceof Type.ArrayT arr ? arr.len() + "u" : "p->len";
        helpers.append("static void ").append(name).append("(").append(ct(t)).append(" *r, const ").append(ct(parts))
            .append(" *p, const uint8_t *sep, uint32_t sn, int line, int col) {\n")
            .append("    uint32_t i;\n")
            .append("    uint64_t need = 0;\n")
            .append("    for (i = 0; i < ").append(n).append("; i++) need += p->v[i].len + (i > 0 ? sn : 0);\n")
            .append("    if (need > ").append(t.cap()).append("u) al_need_trap(\"join\", need, ").append(t.cap()).append("u, line, col);\n")
            .append("    r->len = 0;\n")
            .append("    for (i = 0; i < ").append(n).append("; i++) {\n")
            .append("        if (i > 0) r->len += al_copy_bytes(r->b + r->len, sep, sn);\n")
            .append("        r->len += al_copy_bytes(r->b + r->len, p->v[i].b, p->v[i].len);\n")
            .append("    }\n")
            .append("}\n\n");
        return name;
    }

    // =================================================================== text helpers

    private String text(Span s) {
        String t = (s.file() != null ? s.file() : source).text(s);
        return t.isEmpty() ? "?" : t;
    }

    private static byte[] utf8(String s) {
        return s.getBytes(StandardCharsets.UTF_8);
    }

    /** A C string literal; escapes everything that could be misread (including trigraphs). */
    static String cString(byte[] bytes) {
        StringBuilder sb = new StringBuilder("\"");
        for (byte x : bytes) {
            int c = x & 0xFF;
            switch (c) {
                case '"' -> sb.append("\\\"");
                case '\\' -> sb.append("\\\\");
                case '?' -> sb.append("\\?");
                default -> {
                    if (c >= 0x20 && c < 0x7F) sb.append((char) c);
                    else sb.append('\\').append((char) ('0' + (c >> 6))).append((char) ('0' + ((c >> 3) & 7))).append((char) ('0' + (c & 7)));
                }
            }
        }
        return sb.append('"').toString();
    }

    private static String comment(String s) {
        return s.replace("*/", "* /");
    }
